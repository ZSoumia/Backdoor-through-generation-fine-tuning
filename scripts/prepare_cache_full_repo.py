#!/usr/bin/env python3
"""Prepare and verify external resources for offline Leonardo experiments.

This script stages resources; it does NOT build poisoning JSONL tables or install
Python packages.

Examples:
    python scripts/prepare_cache.py list
    python scripts/prepare_cache.py prepare --cache-root /leonardo_work/try26_zuziak
    python scripts/prepare_cache.py check --cache-root /leonardo_work/try26_zuziak
    python scripts/prepare_cache.py prepare --scope study --only models --cache-root /leonardo_work/try26_zuziak
    source /leonardo_work/try26_zuziak/bdsurvive_cache_env.sh
"""
from __future__ import annotations

import argparse
import json
import os
import shlex
import shutil
import sys
from pathlib import Path
import yaml
from huggingface_hub import snapshot_download
from transformers import AutoConfig, AutoTokenizer
from sentence_transformers import SentenceTransformer
from datasets import load_dataset
import stanza
from OpenAttack import DataManager

PROJECT_ROOT = Path(__file__).resolve().parents[1]
# Unlike the full-model training dependency set, BITE also needs these models.
BITE_MLM = "distilroberta-base"
BITE_ENCODER = "sentence-transformers/all-MiniLM-L6-v2"
SCPN_ASSET = "AttackAssist.SCPN"
SCPN_FILES = (
    "scpn.pt", "parse_generator.pt", "parse_vocab.pkl",
    "bpe.codes", "vocab.txt", "ptb_tagset.pkl",
)
# Exclude TensorFlow/Flax weights while retaining both PyTorch and safetensors.
MODEL_PATTERNS = (
    "*.json", "*.txt", "*.model", "*.tiktoken", "*.vocab",
    "*.py", "*.jinja", "*.spm", "*.safetensors", "pytorch_model*.bin",
)
DATASETS = {
    "ag_news": ("fancyzhx/ag_news", None, ("train", "test")),
    "sst2": ("nyu-mll/glue", "sst2", ("train", "validation")),
}
CATEGORIES = ("models", "datasets", "bite", "syntactic")


def discover(study_files: list[Path], manifests: list[Path], extra_models: list[str],
             extra_tasks: list[str], include_all_tasks: bool,
             mechanisms_file: Path | None = None) -> tuple[list[tuple[str, str | None]], list[str]]:
    """Derive external resources from study YAMLs, manifests, and optional registry.

    The mechanism registry has additional models not present in section1_grid.
    All supported datasets are included in the full-repository scope even when
    the current study YAMLs only name AG News.
    """
   

    models: set[tuple[str, str | None]] = set()
    tasks: set[str] = set(extra_tasks)
    for study_file in study_files:
        study = yaml.safe_load(study_file.read_text(encoding="utf-8")) or {}
        for m in study.get("model", []):
            if isinstance(m, dict):
                models.add((m["name"], m.get("revision")))
            elif isinstance(m, str):
                models.add((m, None))
        shared_data = (study.get("shared", {}) or {}).get("data", {}) or {}
        for key in ("planting_task", "lineage_task"):
            if shared_data.get(key):
                tasks.add(shared_data[key])
    if mechanisms_file is not None:
        registry = yaml.safe_load(mechanisms_file.read_text(encoding="utf-8")) or {}
        for record in registry.values():
            if not isinstance(record, dict):
                continue
            plant = record.get("plant") or {}
            if plant.get("base_model"):
                models.add((plant["base_model"], None))
            if plant.get("task"):
                tasks.add(plant["task"])
    for manifest in manifests:
        with manifest.open(encoding="utf-8") as handle:
            for line in handle:
                if not line.strip():
                    continue
                row = json.loads(line)
                config = row.get("config") or {}
                model = config.get("model") or {}
                name = model.get("name") or row.get("model")
                if name:
                    models.add((name, model.get("revision")))
                data = config.get("data") or {}
                for task in (data.get("planting_task"), data.get("lineage_task"),
                             row.get("planting_task"), row.get("lineage_task")):
                    if task:
                        tasks.add(task)
    models.update((name, None) for name in extra_models)
    if include_all_tasks:
        tasks.update(DATASETS)
    unknown = tasks - DATASETS.keys()
    if unknown:
        raise ValueError(f"Unsupported tasks in this repository: {', '.join(sorted(unknown))}")
    return sorted(models, key=lambda x: (x[0], x[1] or "")), sorted(tasks)


def paths_for(root: Path) -> dict[str, Path]:
    return {
        "HF_HOME": root / "hf_cache",
        "STANZA_RESOURCES_DIR": root / "stanza_resources",
        "OPENATTACK_DATA_DIR": root / "openattack_data",
    }


def env_file_contents(paths: dict[str, Path]) -> str:
    lines = ["# Generated by scripts/prepare_cache.py; source before offline jobs."]
    for key, value in paths.items():
        lines.append(f"export {key}={shlex.quote(str(value))}")
    lines.extend((
        "export HF_HUB_OFFLINE=1",
        "export HF_DATASETS_OFFLINE=1",
        "export TRANSFORMERS_OFFLINE=1",
    ))
    return "\n".join(lines) + "\n"


def check_model_weights(snapshot: Path) -> str:
    for index_name in ("model.safetensors.index.json", "pytorch_model.bin.index.json"):
        index = snapshot / index_name
        if index.is_file():
            mapping = json.loads(index.read_text(encoding="utf-8")).get("weight_map", {})
            shards = set(mapping.values())
            if not shards or any(not (snapshot / shard).is_file() for shard in shards):
                raise RuntimeError(f"Missing shards referenced by {index_name}")
            if any((snapshot / shard).stat().st_size == 0 for shard in shards):
                raise RuntimeError(f"Empty weight shard referenced by {index_name}")
            return f"{len(shards)} weight shard(s)"
    for filename in ("model.safetensors", "pytorch_model.bin"):
        if (snapshot / filename).is_file() and (snapshot / filename).stat().st_size > 0:
            return filename
    raise RuntimeError(f"Missing safetensors/PyTorch model weights in {snapshot}")


def fetch_hf_model(name: str, revision: str | None, offline: bool,
                   sentence_encoder: bool = False) -> str:
   

    path = Path(name)
    if path.is_dir():
        snapshot = path
    else:
        snapshot = Path(snapshot_download(
            repo_id=name, revision=revision, allow_patterns=list(MODEL_PATTERNS),
            local_files_only=offline, max_workers=2,
        ))
    if sentence_encoder:
        # A sentence-transformers folder has additional modules.json and pooling files.
        # Check actual local initialization, not merely its transformer weights.
        
        SentenceTransformer(str(snapshot), device="cpu")
    else:
        AutoConfig.from_pretrained(str(snapshot), local_files_only=True)
        AutoTokenizer.from_pretrained(str(snapshot), local_files_only=True)
    return f"{check_model_weights(snapshot)} at {snapshot}"


def fetch_dataset(task: str) -> str:
   
    name, config, splits = DATASETS[task]
    counts = []
    for split in splits:
        if config is None:
            ds = load_dataset(name, split=split)
        else:
            ds = load_dataset(name, config, split=split)
        if not len(ds):
            raise RuntimeError(f"{task}:{split} is empty")
        counts.append(f"{split}={len(ds)}")
    return ", ".join(counts)


def fetch_stanza(offline: bool) -> str:
  
    folder = Path(os.environ["STANZA_RESOURCES_DIR"])
    # Matches the HiddenKiller builder's pipeline, including PTB3 labels.
    processors = {"tokenize": "default", "pos": "default", "constituency": "ptb3_charlm"}
    if not offline:
        stanza.download("en", processors=processors, package=None, model_dir=str(folder))
    nlp = stanza.Pipeline(
        "en", processors="tokenize,pos,constituency",
        package={"constituency": "ptb3_charlm"},
        dir=str(folder), download_method=None, use_gpu=False,
    )
    parsed = nlp("This is a test.")
    if not parsed.sentences or parsed.sentences[0].constituency is None:
        raise RuntimeError("Stanza constituency parsing produced no tree")
    return f"English PTB3 constituency parsed offline from {folder}"


def fetch_scpn(offline: bool) -> str:
    

    folder = Path(os.environ["OPENATTACK_DATA_DIR"]) / SCPN_ASSET
    # Earlier versions of this repository used OpenAttack's cwd/data default.
    # Reuse completed legacy assets instead of downloading them a second time.
    legacy = PROJECT_ROOT / "data" / SCPN_ASSET
    if not folder.is_dir() and legacy.is_dir() and not offline:
        if all((legacy / name).is_file() and (legacy / name).stat().st_size > 0
               for name in SCPN_FILES):
            shutil.copytree(legacy, folder, dirs_exist_ok=True)
            print(f"  Reused existing OpenAttack assets from {legacy}", flush=True)

    DataManager.set_path(str(folder), SCPN_ASSET)
    DataManager.setAutoDownload(False)
    if not offline:
        # DataManager.download() skips any existing directory, even if it is
        # incomplete. Force a repair only when the known SCPN files are absent.
        complete = all((folder / name).is_file() and (folder / name).stat().st_size > 0
                       for name in SCPN_FILES)
        if not complete:
            DataManager.enable_cdn()
            DataManager.download(SCPN_ASSET, force=folder.exists())
    files = DataManager.load(SCPN_ASSET, cached=False)
    missing = [name for name in SCPN_FILES
               if name not in files or not Path(files[name]).is_file()
               or Path(files[name]).stat().st_size == 0]
    if missing:
        raise RuntimeError(f"SCPN missing/empty asset(s): {', '.join(missing)}")
    return f"{len(SCPN_FILES)} SCPN assets at {folder}"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("mode", choices=("list", "prepare", "check"))
    p.add_argument("--scope", choices=("all", "study"), default="all",
                   help="all: include mechanisms registry, existing manifests and SST-2; study: study YAMLs only")
    p.add_argument("--cache-root", type=Path, default=Path(os.environ.get("BDS_CACHE_ROOT") or
                   os.environ.get("WORK") or os.getcwd()), help="Persistent shared root, not a node-local scratch directory")
    p.add_argument("--study", type=Path, action="append", default=None,
                   help="Study YAML; repeat to override the default configs/study/*.yaml discovery")
    p.add_argument("--manifest", type=Path, action="append", default=[], help="Additional JSONL manifest")
    p.add_argument("--model", action="append", default=[], help="Additional Hugging Face model")
    p.add_argument("--task", action="append", default=[], help="Additional task (ag_news or sst2)")
    p.add_argument("--all-tasks", action="store_true", help="Include every supported dataset even in study scope")
    p.add_argument("--only", action="append", choices=CATEGORIES, default=[],
                   help="Restrict categories; repeatable")
    args = p.parse_args(argv)

    studies = args.study if args.study is not None else sorted((PROJECT_ROOT / "configs" / "study").glob("*.yaml"))
    registry = PROJECT_ROOT / "configs" / "mechanisms.yaml"
    mechanisms = registry if args.scope == "all" and registry.is_file() else None
    manifests = list(args.manifest)
    if args.scope == "all":
        manifests.extend(sorted((PROJECT_ROOT / "manifests").glob("*.jsonl")))
        manifests.extend(sorted(PROJECT_ROOT.glob("manifest*.jsonl")))
    manifests = sorted(set(manifests))
    try:
        models, tasks = discover(studies, manifests, args.model, args.task,
                                 args.all_tasks or args.scope == "all", mechanisms)
    except Exception as exc:
        p.error(str(exc))
    categories = args.only or list(CATEGORIES)
    root = args.cache_root.expanduser().resolve()
    paths = paths_for(root)
    print(f"Shared cache root: {root}", flush=True)
    print(f"Scope: {args.scope} | study files: {len(studies)} | manifests: {len(manifests)} "
          f"| mechanism registry: {bool(mechanisms)}")
    print(f"Model(s): {len(models)} | task(s): {len(tasks)}")
    print(f"Selected: {', '.join(categories)}")
    for name, revision in models:
        print(f"  model: {name}" + (f" @ {revision}" if revision else ""))
    for task in tasks:
        print(f"  dataset: {task}")
    if "bite" in categories:
        print(f"  BITE: {BITE_MLM}, {BITE_ENCODER}")
    if "syntactic" in categories:
        print(f"  syntactic: Stanza en/ptb3_charlm, {SCPN_ASSET}")
    if args.mode == "list":
        return 0

    if args.mode == "prepare":
        # Running prepare should be idempotent, including if the user sourced
        # our offline environment file for a prior job in this shell.
        for key in ("HF_HUB_OFFLINE", "HF_DATASETS_OFFLINE", "TRANSFORMERS_OFFLINE"):
            os.environ.pop(key, None)
    for key, value in paths.items():
        os.environ[key] = str(value)
        if args.mode == "prepare":
            value.mkdir(parents=True, exist_ok=True)
    if args.mode == "check":
        # Must happen before importing any of the HF libraries.
        for key in ("HF_HUB_OFFLINE", "HF_DATASETS_OFFLINE", "TRANSFORMERS_OFFLINE"):
            os.environ[key] = "1"

    failures = []

    def attempt(label: str, operation) -> None:
        print(f"\n[{args.mode.upper()}] {label}", flush=True)
        try:
            print("  PASS: " + operation(), flush=True)
        except Exception as exc:
            failures.append(label)
            print(f"  FAIL: {type(exc).__name__}: {exc}", file=sys.stderr, flush=True)

    offline = args.mode == "check"
    if "models" in categories:
        for name, revision in models:
            attempt(f"model {name}", lambda n=name, r=revision: fetch_hf_model(n, r, offline))
    if "datasets" in categories:
        for task in tasks:
            attempt(f"dataset {task}", lambda t=task: fetch_dataset(t))
    if "bite" in categories:
        attempt("BITE masked LM", lambda: fetch_hf_model(BITE_MLM, None, offline))
        attempt("BITE encoder", lambda: fetch_hf_model(BITE_ENCODER, None, offline, sentence_encoder=True))
    if "syntactic" in categories:
        attempt("Stanza parser", lambda: fetch_stanza(offline))
        attempt("OpenAttack SCPN", lambda: fetch_scpn(offline))

    if args.mode == "prepare":
        env_path = root / "bdsurvive_cache_env.sh"
        # Avoid leaving a partially written env file on shared storage.
        tmp_env = env_path.with_suffix(".sh.tmp")
        tmp_env.write_text(env_file_contents(paths), encoding="utf-8")
        tmp_env.replace(env_path)
        print(f"\nOffline job environment saved: {env_path}")
    if failures:
        print(f"\nFAILED ({len(failures)}): {', '.join(failures)}", file=sys.stderr)
        return 1
    print(f"\nPASS: all selected external resources {'prepared' if args.mode == 'prepare' else 'checked'} successfully")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
